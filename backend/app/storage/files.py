"""Where the ORIGINAL uploaded PDF bytes live (separate from the chunks and metadata, which
live in the ChunkStore).

Why a separate store: the PDF viewer needs the original file, and free hosts wipe their disk
on every restart. So there are two implementations behind one small interface:

    LocalFileStore   a folder on disk. Great for development. Lost when a free host restarts.
    GridFSFileStore  MongoDB's built-in file storage. Survives restarts; same DB as everything else.

The API only ever talks to `FileStore`, so switching is one env var: FILE_STORE=local|mongo.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Protocol

from app.config import Settings

# Document ids are generated by us (hex), but they also arrive in URLs (GET /documents/<id>/file).
# Never trust text from a URL when building a file path: this blocks "../../etc/passwd".
_SAFE_ID = re.compile(r"^[A-Za-z0-9_-]{1,64}$")


def _check_id(doc_id: str) -> None:
    if not _SAFE_ID.match(doc_id):
        raise ValueError(f"invalid document id: {doc_id!r}")


class FileStore(Protocol):
    def save(self, doc_id: str, data: bytes) -> None:
        """Store the bytes under doc_id. Saving the same id again replaces the old file."""
        ...

    def read(self, doc_id: str) -> bytes | None:
        """The stored bytes, or None if there is no such file (also None for an invalid id)."""
        ...

    def delete(self, doc_id: str) -> None:
        """Remove the file. Deleting a file that does not exist is not an error."""
        ...


class LocalFileStore:
    def __init__(self, root: Path):
        self.root = root

    def _path(self, doc_id: str) -> Path:
        _check_id(doc_id)
        return self.root / f"{doc_id}.pdf"

    def save(self, doc_id: str, data: bytes) -> None:
        path = self._path(doc_id)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def read(self, doc_id: str) -> bytes | None:
        try:
            path = self._path(doc_id)
        except ValueError:
            return None
        return path.read_bytes() if path.exists() else None

    def delete(self, doc_id: str) -> None:
        try:
            self._path(doc_id).unlink(missing_ok=True)
        except ValueError:
            pass


class GridFSFileStore:
    """PDFs stored in MongoDB via GridFS: files bigger than 16 MB are split into chunks
    automatically, and each file keeps its id, name and content type."""

    def __init__(self, uri: str, db_name: str, client=None):
        import gridfs  # lazy: only needed when FILE_STORE=mongo
        import pymongo

        self._gridfs = gridfs
        self._client = client or pymongo.MongoClient(uri)
        self._fs = gridfs.GridFS(self._client[db_name], collection="pdfs")

    def save(self, doc_id: str, data: bytes) -> None:
        _check_id(doc_id)
        if self._fs.exists(doc_id):  # GridFS refuses a second file with the same _id
            self._fs.delete(doc_id)
        self._fs.put(data, _id=doc_id, filename=f"{doc_id}.pdf", contentType="application/pdf")

    def read(self, doc_id: str) -> bytes | None:
        if not _SAFE_ID.match(doc_id):
            return None
        try:
            return self._fs.get(doc_id).read()
        except self._gridfs.errors.NoFile:
            return None

    def delete(self, doc_id: str) -> None:
        if _SAFE_ID.match(doc_id):
            self._fs.delete(doc_id)  # deleting a missing id is a no-op in GridFS


def build_file_store(settings: Settings) -> FileStore:
    if settings.file_store == "mongo":
        return GridFSFileStore(settings.mongo_uri, settings.mongo_db)
    return LocalFileStore(settings.data_dir / "uploads")
